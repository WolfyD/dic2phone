/// Symbols printed on the deck. The variation selector (U+FE0E) after some of them keeps iOS
/// from drawing them as colour emoji.
enum Glyph {
    static let rec = "●"
    static let play = "▶\u{FE0E}"
    static let pause = "❚❚"
    static let rewind = "◀\u{FE0E}◀\u{FE0E}"
    static let fastForward = "▶\u{FE0E}▶\u{FE0E}"
    static let eject = "⏏\u{FE0E}"
    static let flag = "⚑"
    static let previousFlag = "◀\u{FE0E}⚑"
    static let nextFlag = "⚑▶\u{FE0E}"
    static let setup = "⚙\u{FE0E}"
    static let warning = "⚠\u{FE0E}"
    static let stop = "■"
    static let inDeck = "◉"
    static let check = "✔\u{FE0E}"
    static let close = "✕"
    static let sort = "↕\u{FE0E}"
    static let back = "◀\u{FE0E}"
    static let search = "⌕"
    static let chosen = "●"
    static let notChosen = "○"
    static let folded = "▸"
    static let unfolded = "▾"
    static let lidClosed = "▾"
    static let lidOpen = "▴"
    /// Padlocks have no plain-text form on iOS; they show as emoji, as they do on Android.
    static let locked = "🔒"
    static let unlocked = "🔓"
}
